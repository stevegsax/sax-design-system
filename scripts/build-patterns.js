// scripts/build-patterns.js
//
// Emits dist/patterns/<situation>.html — every shipped pattern rendered
// statically under that situation's tokens, with its usage line. The same
// content the Storybook Patterns story shows, shareable without a dev
// server. Part of the dist navigation rationalization: linked from the
// home page, cross-linked per situation.

import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { NAV_CSS, navStrip } from './lib/site-nav.js';

const ROOT = path.resolve(import.meta.dirname, '..');
const matrix = JSON.parse(readFileSync(path.join(ROOT, 'config/matrix.json'), 'utf8'));
const pkg = JSON.parse(readFileSync(path.join(ROOT, 'package.json'), 'utf8'));

// Render order: small controls first, the full-page shell last.
const ORDER = ['button', 'field', 'card', 'alert', 'tag', 'callout', 'page-shell-application'];

const header = (html) => {
  const comment = html.match(/^<!--([\s\S]*?)-->/)?.[1] ?? '';
  const fields = {};
  for (const line of comment.split('\n')) {
    const m = line.match(/^\s*([a-z-]+):\s*(.+)$/);
    if (m) fields[m[1]] = m[2].trim();
  }
  return fields;
};

const available = readdirSync(path.join(ROOT, 'patterns')).filter((f) => f.endsWith('.html'));
const names = [
  ...ORDER.filter((n) => available.includes(`${n}.html`)),
  ...available.map((f) => path.basename(f, '.html')).filter((n) => !ORDER.includes(n)).sort(),
];

const sections = names
  .map((name) => {
    const raw = readFileSync(path.join(ROOT, 'patterns', `${name}.html`), 'utf8');
    const usage = header(raw).usage ?? '';
    const body = raw
      .replace(/^<!--[\s\S]*?-->\s*/, '')
      .replaceAll('../static-assets/logos/symbol-only/SAX_logo_symbol.svg', '../sax-logo-symbol.svg');
    return `<section class="pattern">
  <h2><code>${name}</code></h2>
  <p class="usage">${usage}</p>
  <div class="render">
${body}
  </div>
</section>`;
  })
  .join('\n');

const outDir = path.join(ROOT, 'dist', 'patterns');
mkdirSync(outDir, { recursive: true });

for (const situation of matrix.situations) {
  const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${pkg.name} — patterns under ${situation}</title>
<link rel="stylesheet" href="../tokens.css">
<link rel="stylesheet" href="../base.css">
<style>
  body { margin: 0; }
  ${NAV_CSS}
  main { max-width: none; margin: 0; padding: var(--space-lg) var(--container-gutter); }
  .pattern { margin-block-end: var(--rhythm-section); }
  .pattern > h2 { margin-block-end: var(--space-2xs); }
  .usage { color: var(--color-text-muted); font: var(--typography-body-small); max-width: 44rem; }
  .render { border: var(--border-width-default) dashed var(--color-border-strong);
            border-radius: var(--radius-md); padding: var(--space-lg); }
</style>
</head>
<body data-situation="${situation}">
${navStrip({
    depth: '../',
    here: 'patterns',
    links: [
      ...matrix.situations.map((s) => ({ label: s, href: `${s}.html`, current: s === situation })),
      { label: 'token catalog →', href: `../catalog/${situation}.html` },
    ],
  })}
<main>
<h1>Patterns under <code>${situation}</code></h1>
<p class="usage">Every shipped pattern (patterns/*.html), rendered with this
situation's tokens and base.css. Generated by ${pkg.name} v${pkg.version}.</p>
${sections}
</main>
</body>
</html>
`;
  writeFileSync(path.join(outDir, `${situation}.html`), html);
  console.log(`dist/patterns/${situation}.html`);
}
