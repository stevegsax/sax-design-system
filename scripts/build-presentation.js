const outDir = path.join(ROOT, 'dist', SITUATION);
mkdirSync(outDir, { recursive: true });
const revealDist = path.join(ROOT, 'node_modules/reveal.js/dist');
for (const asset of ['reveal.css', 'reveal.js', 'reset.css']) {
  copyFileSync(path.join(revealDist, asset), path.join(outDir, asset));
}
// reveal's syntax-highlighting plugin (bundles highlight.js). Its color theme
// is ours: highlight.css, not the stock monokai/zenburn.
copyFileSync(path.join(revealDist, 'plugin/highlight.js'), path.join(outDir, 'highlight.js'));
copyFileSync(
  path.join(ROOT, 'static-assets/logos/symbol-only/SAX_logo_symbol.svg'),
  path.join(outDir, 'sax-logo-symbol.svg'),
);
// The kit is copied or served as a directory, so it carries its own copy of the
// system stylesheet (build:tokens runs first in the build chain).
copyFileSync(path.join(ROOT, 'dist', 'tokens.css'), path.join(outDir, 'tokens.css'));
writeFileSync(path.join(outDir, 'theme.css'), THEME);
writeFileSync(path.join(outDir, 'highlight.css'), HIGHLIGHT);
